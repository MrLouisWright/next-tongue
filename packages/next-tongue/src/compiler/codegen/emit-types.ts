import type { InferredArgs } from '../ast.js';

export type NamespaceTypes = Record<string, Record<string, InferredArgs>>;

export function emitTypesFile(opts: {
  locales: readonly string[];
  namespaces: NamespaceTypes;
  pathnames?: string[];
}): string {
  const localeUnion = opts.locales.map((l) => JSON.stringify(l)).join(' | ');
  const nsLines: string[] = [];
  for (const [ns, keys] of Object.entries(opts.namespaces).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const keyLines: string[] = [];
    for (const [key, args] of Object.entries(keys).sort(([a], [b]) =>
      a.localeCompare(b),
    )) {
      keyLines.push(`      ${JSON.stringify(key)}: ${argsToType(args)};`);
    }
    const nsName = ns === '_root' ? '_root' : ns;
    nsLines.push(`    ${JSON.stringify(nsName)}: {\n${keyLines.join('\n')}\n    };`);
  }

  const pathnames =
    opts.pathnames && opts.pathnames.length
      ? opts.pathnames.map((p) => JSON.stringify(p)).join(' | ')
      : 'string';

  return `/* eslint-disable */
// Generated by next-tongue. Do not edit.
import type { ReactNode } from 'react';
declare module 'next-tongue' {
  interface TongueRegister {
    locales: ${localeUnion};
    ns: {
${nsLines.join('\n')}
    };
    pathnames: ${pathnames};
  }
}
export {};
`;
}

function argsToType(args: InferredArgs): string {
  const entries = Object.entries(args);
  if (entries.length === 0) return 'Record<string, never>';
  const fields = entries.map(([name, kind]) => {
    switch (kind.kind) {
      case 'string':
        return `${JSON.stringify(name)}: string | number`;
      case 'number':
        return `${JSON.stringify(name)}: number`;
      case 'bigint-number':
        return `${JSON.stringify(name)}: number | bigint`;
      case 'date':
        return `${JSON.stringify(name)}: Date | number`;
      case 'select': {
        const lits = kind.options.map((o) => JSON.stringify(o)).join(' | ');
        return `${JSON.stringify(name)}: ${lits}${lits ? ' | ' : ''}(string & {})`;
      }
      case 'rich':
        return kind.selfClosing
          ? `${JSON.stringify(name)}: () => ReactNode`
          : `${JSON.stringify(name)}: (chunks: ReactNode) => ReactNode`;
    }
  });
  return `{ ${fields.join('; ')} }`;
}
