import { LruCache } from '../runtime/lru.js';

export type LocaleMatcherTables = {
  /** lowercase tag → canonical configured locale */
  exact: Record<string, string>;
  /** language subtag → preferred configured locale (first match) */
  byLanguage: Record<string, string>;
};

export type LocaleMatcher = {
  /** Match an Accept-Language header; no Intl.* construction. */
  match: (header: string | null) => string | undefined;
  /** Precomputed tables (for codegen / tests). */
  tables: LocaleMatcherTables;
};

export type CreateLocaleMatcherOptions = {
  /** Bounded LRU of header → locale (default 200). */
  cacheSize?: number;
};

/**
 * Build lookup tables once from the configured locale list.
 * Exact tags, parent-chain walk, then language best-fit — no Intl (#18).
 */
export function buildLocaleMatcherTables(
  locales: readonly string[],
): LocaleMatcherTables {
  const exact: Record<string, string> = {};
  const byLanguage: Record<string, string> = {};
  for (const locale of locales) {
    const lower = locale.toLowerCase();
    exact[lower] = locale;
    const lang = lower.split('-')[0]!;
    if (!(lang in byLanguage)) byLanguage[lang] = locale;
  }
  return { exact, byLanguage };
}

/** Parent tags from most specific to language-only (`zh-hant-hk` → … → `zh`). */
export function localeParentChain(tag: string): string[] {
  const parts = tag.toLowerCase().split('-').filter(Boolean);
  const chain: string[] = [];
  for (let i = parts.length; i >= 1; i--) {
    chain.push(parts.slice(0, i).join('-'));
  }
  return chain;
}

export function matchTagAgainstTables(
  tag: string,
  tables: LocaleMatcherTables,
): string | undefined {
  if (!tag || tag === '*') return undefined;
  for (const candidate of localeParentChain(tag)) {
    const hit = tables.exact[candidate];
    if (hit) return hit;
  }
  const lang = tag.toLowerCase().split('-')[0]!;
  return tables.byLanguage[lang];
}

/**
 * Create a matcher with a bounded Accept-Language LRU.
 * Safe to call once at `createProxy` init — never per request.
 */
export function createLocaleMatcher(
  locales: readonly string[],
  options: CreateLocaleMatcherOptions = {},
): LocaleMatcher {
  const tables = buildLocaleMatcherTables(locales);
  const cache = new LruCache<string, string | null>(options.cacheSize ?? 200);

  function match(header: string | null): string | undefined {
    if (!header) return undefined;
    const hit = cache.get(header);
    if (hit !== undefined) return hit === null ? undefined : hit;

    const parts = header.split(',').map((p) => {
      const [rawTag, ...params] = p.trim().split(';');
      let q = 1;
      for (const param of params) {
        const m = /q\s*=\s*([\d.]+)/i.exec(param);
        if (m) q = Number(m[1]);
      }
      return { tag: (rawTag ?? '').trim().toLowerCase(), q };
    });
    parts.sort((a, b) => b.q - a.q);

    let result: string | undefined;
    for (const { tag } of parts) {
      const found = matchTagAgainstTables(tag, tables);
      if (found) {
        result = found;
        break;
      }
    }
    cache.set(header, result ?? null);
    return result;
  }

  return { match, tables };
}

/** Emit JS source for `.tongue/locale-matcher.js` (codegen). */
export function emitLocaleMatcherModule(locales: readonly string[]): string {
  const tables = buildLocaleMatcherTables(locales);
  return [
    `/** Generated by next-tongue — do not edit. */`,
    `export const exact = ${JSON.stringify(tables.exact)};`,
    `export const byLanguage = ${JSON.stringify(tables.byLanguage)};`,
    `export const locales = ${JSON.stringify([...locales])};`,
    ``,
  ].join('\n');
}
